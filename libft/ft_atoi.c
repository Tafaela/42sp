#include "libft.h"

int	ft_atoi(const char *nptr)
{
	const char	*q;
	int			s;
	int			r;

	q = nptr;
	s = 1;
	while (*q == ' ' || (*q >= 9 && *q <= 13))
		q++;
	if (*q == '-' || *q == '+')
	{
		if (*q == '-')
			s = -1;
		q++;
	}
	r = 0;
	while (*q >= '0' && *q <= '9')
	{
		r = (r * 10) + (*q - '0');
		q++;
	}
	return (r * s);
}
